def resolve_confirmation(confirm_id: str, approved: bool) -> dict[str, Any]:
    """Execute or reject a pending delete/move confirmation."""
    pending = _pending_confirms.pop(confirm_id, None)
    if not pending:
        return {"error": f"No pending confirmation with id '{confirm_id}'"}

    if not approved:
        return {"cancelled": True, "message": "Operation cancelled by user."}

    op = pending["operation"]
    if op == "delete":
        from tools.files import op_delete
        return op_delete(pending["path"])
    elif op == "move":
        from tools.files import op_move
        return op_move(pending["source"], pending["destination"])
    return {"error": f"Unknown operation: {op}"}


async def _detect_backend() -> str:
    groq_ok = await _check_groq()
    if groq_ok:
        return "groq"
    ollama_ok = await _check_ollama()
    if ollama_ok:
        return "ollama"
    raise RuntimeError("No LLM backend available. Check GROQ_API_KEY or start Ollama.")


def _history_to_messages(history: list[dict[str, Any]], limit: int = 20) -> list:
    msgs = []
    for m in history[-limit:]:
        role = m.get("role", "user")
        content = m.get("content", "")
        if role == "user":
            msgs.append(HumanMessage(content=content))
        elif role in ("assistant", "agent"):
            msgs.append(AIMessage(content=content))
    return msgs


async def nila_stream(
    user_text: str,
    history: list[dict[str, Any]],
    model_backend: str | None = None,
) -> AsyncGenerator[dict[str, Any], None]:
    """Stream Nila's response with tool calls as SSE-friendly dicts."""
    from memory.database import get_all_facts

    backend = model_backend or await _detect_backend()
    llm = get_llm(backend)
    llm_with_tools = llm.bind_tools(ALL_TOOLS)

    facts = await get_all_facts()
    system_prompt = _build_system_prompt(facts)

    messages: list = [SystemMessage(content=system_prompt)]
    messages.extend(_history_to_messages(history))
    messages.append(HumanMessage(content=user_text))

    tool_map = {t.name: t for t in ALL_TOOLS}
    generated_files: list[dict[str, Any]] = []
    max_iterations = 8

    for _ in range(max_iterations):
        full_text = ""
        gathered: AIMessage | None = None

        async for chunk in llm_with_tools.astream(messages):
            if isinstance(chunk, AIMessage):
                gathered = chunk if gathered is None else gathered + chunk
                if chunk.content:
                    text_piece = chunk.content if isinstance(chunk.content, str) else str(chunk.content)
                    full_text += text_piece
                    yield {"type": "token", "text": text_piece}
            elif hasattr(chunk, "content") and chunk.content:
                text_piece = chunk.content if isinstance(chunk.content, str) else str(chunk.content)
                full_text += text_piece
                yield {"type": "token", "text": text_piece}

        tool_calls = gathered.tool_calls if gathered and gathered.tool_calls else []
        ai_msg = AIMessage(content=full_text, tool_calls=tool_calls)
        messages.append(ai_msg)

        if not tool_calls:
            break

        for tc in tool_calls:
            tool_name = tc["name"]
            tool_args = tc["args"]

            # Inject session's model_backend into vision/complex tools
            if tool_name in ("look_at_screen", "analyze_image", "run_complex_task"):
                tool_args = {**tool_args, "_model_backend": backend}

            yield {"type": "tool_start", "name": tool_name}

            try:
                tool_fn = tool_map.get(tool_name)
                if tool_fn is None:
                    result = {"error": f"Unknown tool: {tool_name}"}
                elif asyncio.iscoroutinefunction(tool_fn.func):
                    result = await tool_fn.ainvoke(tool_args)
                else:
                    result = await asyncio.to_thread(tool_fn.invoke, tool_args)

                result_str = json.dumps(result) if isinstance(result, dict) else str(result)

                # Emit confirm_request SSE for delete/move pending confirmations
                if isinstance(result, dict) and result.get("pending_confirmation"):
                    yield {
                        "type": "confirm_request",
                        "id": result["confirm_id"],
                        "message": result["message"],
                    }

                output_path = None
                if isinstance(result, dict) and tool_name in _CREATE_TOOLS:
                    output_path = result.get("output_path")
                    if output_path:
                        file_name = result.get("file_name", output_path.split("\\")[-1].split("/")[-1])
                        file_type = result.get("file_type", "file")
                        generated_files.append({
                            "file_path": output_path,
                            "file_name": file_name,
                            "file_type": file_type,
                            "status": "created",
                        })
                    if result.get("generated_outputs"):
                        generated_files.extend(result["generated_outputs"])

                yield {"type": "tool_end", "name": tool_name, "output_path": output_path}
                messages.append(ToolMessage(content=result_str, tool_call_id=tc["id"]))

            except Exception as exc:
                err = f"Error running {tool_name}: {exc}"
                logger.exception(err)
                yield {"type": "tool_end", "name": tool_name, "output_path": None, "error": str(exc)}
                messages.append(ToolMessage(content=json.dumps({"error": str(exc)}), tool_call_id=tc["id"]))

    final_text = ""
    for m in reversed(messages):
        if isinstance(m, AIMessage) and m.content and not m.tool_calls:
            final_text = m.content if isinstance(m.content, str) else str(m.content)
            break

    yield {"type": "message", "content": final_text, "generated_files": generated_files}
    yield {"type": "done"}
