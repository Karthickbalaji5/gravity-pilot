@tool
def create_word_document(filename: str, title: str, sections: list[dict[str, Any]]) -> dict[str, Any]:
    """Create a Microsoft Word document (.docx).

    Args:
        filename: Output filename (e.g. "report.docx").
        title: Document title.
        sections: List of {"heading": "...", "paragraphs": ["paragraph 1", "paragraph 2"]} sections. Each section has a heading and a list of paragraph strings.
    """
    from tools.documents import generate_word_doc
    converted = []
    for s in sections:
        heading = s.get("heading", "")
        if "paragraphs" in s and isinstance(s["paragraphs"], list):
            paras = s["paragraphs"]
        elif "body" in s:
            paras = [p.strip() for p in s["body"].split("\n\n") if p.strip()]
            if not paras:
                paras = [s["body"]]
        else:
            paras = []
        converted.append({"heading": heading, "paragraphs": paras})
    content = {"title": title, "sections": converted}
    path = generate_word_doc(filename, content, output_dir=get_output_dir())
    return {"success": True, "output_path": path, "file_name": filename, "file_type": "docx"}


