@tool
def create_powerpoint(filename: str, title: str, slides: list[dict[str, Any]], subtitle: str = "Generated by Nila") -> dict[str, Any]:
    """Create a Microsoft PowerPoint presentation (.pptx).

    Args:
        filename: Output filename (e.g. "deck.pptx").
        title: Presentation title.
        slides: List of {"title": "...", "bullets": ["bullet 1", "bullet 2"]} slide dicts. Each slide has a title and a list of bullet point strings.
        subtitle: Subtitle for the title slide.
    """
    from tools.documents import generate_powerpoint
    converted = []
    for s in slides:
        slide_title = s.get("title", "Slide")
        if "bullets" in s and isinstance(s["bullets"], list):
            bullets = s["bullets"]
        elif "content" in s:
            bullets = [line.strip() for line in s["content"].split("\n") if line.strip()]
            if not bullets:
                bullets = [s["content"]]
        else:
            bullets = []
        converted.append({"title": slide_title, "bullets": bullets})
    content = {"title": title, "subtitle": subtitle, "slides": converted}
    path = generate_powerpoint(filename, content, output_dir=get_output_dir())
    return {"success": True, "output_path": path, "file_name": filename, "file_type": "pptx"}


